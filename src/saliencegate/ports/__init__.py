def __getattr__(name: str) -> object:
    if name in _LAZY_MODEL_CALL_EXPORTS:
        module_name = "saliencegate.ports.model_calls"
    elif name in _LAZY_TWO_PHASE_EXPORTS:
        module_name = "saliencegate.ports.two_phase"
    else:
        raise AttributeError(name)
    value = getattr(import_module(module_name), name)
    globals()[name] = value
    return value


